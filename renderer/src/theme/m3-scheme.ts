// Vuetify gives every `bg-<color>` class the text color `on-<color>`, and picks black or white
// when that key is missing. M3 pairs these roles differently, so spell the pairs out.
export function toVuetifyColors(scheme: M3Scheme): Record<string, string> {
  return {
    ...scheme,
    "on-surface-dim": scheme["on-surface"],
    "on-surface-bright": scheme["on-surface"],
    "on-surface-container-lowest": scheme["on-surface"],
    "on-surface-container-low": scheme["on-surface"],
    "on-surface-container": scheme["on-surface"],
    "on-surface-container-high": scheme["on-surface"],
    "on-surface-container-highest": scheme["on-surface"],
    "on-inverse-surface": scheme["inverse-on-surface"],
    "on-primary-fixed-dim": scheme["on-primary-fixed"],
    "on-secondary-fixed-dim": scheme["on-secondary-fixed"],
    "on-tertiary-fixed-dim": scheme["on-tertiary-fixed"],
    // Vuetify's own neutral fill (time picker dial and fields, toolbars, ...) takes the nearest M3 role.
    "surface-light": scheme["surface-container-highest"],
    "on-surface-light": scheme["on-surface"],
  };
}
